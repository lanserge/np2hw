"""np2hw.blocks: a model plus what its arithmetic cannot say."""
import functools

import numpy as np
import pytest

from np2hw import saturate
from np2hw.blocks import StreamPort, ContextBit, block, registry, resolve
from np2hw.blocks.params import Context, Param
from np2hw.blocks.stream import StreamSpec

VOCABULARY = {
    "phase": Context(name="phase", bits=2, description="a 2x2 tile phase",
                     even_frame=True),
    "depth": Context(name="depth", bits=5, description="bits in use"),
}
toyblock = functools.partial(block, vocabulary=VOCABULARY)


@toyblock(version=(1, 0), description="add an offset",
          inputs=(StreamPort("in"),), outputs=(StreamPort("out"),),
          consumes=("phase",),
          context=(ContextBit("row", "phase", bit=1),),
          params=[Param("offset", bits=8, default=3,
                        description="what is added", configurable=("bits",))])
def offset(pixel, p, ctx, bit_depth):
    return pixel + p.offset


def test_a_block_is_its_model():
    assert offset(np.array([1, 2]), type("P", (), {"offset": 4}), None,
                  8).tolist() == [5, 6]
    assert offset.name == "offset"
    assert offset.ports.inputs == ("in",) and offset.ports.outputs == ("out",)


def test_run_validates_context_from_the_vocabulary():
    frame = np.full((2, 4), 250, dtype=np.int64)
    assert (offset.run(frame, bit_depth=8, phase=3) == 253).all()
    with pytest.raises(ValueError, match="outside its declared 2-bit range"):
        offset.run(frame, bit_depth=8, phase=4)
    with pytest.raises(TypeError, match="does not consume"):
        offset.run(frame, bit_depth=8, depth=8)


def test_a_signal_that_needs_an_even_frame_refuses_an_odd_one():
    with pytest.raises(ValueError, match="odd dimension"):
        offset.run(np.zeros((3, 4), dtype=np.int64), bit_depth=8)


def test_a_block_without_a_vocabulary_cannot_consume_context():
    @block(version=(1, 0), description="reads a phase it cannot know",
           inputs=(StreamPort("in"),), outputs=(StreamPort("out"),),
           consumes=("phase",),
           params=[Param("k", bits=4, description="unused")])
    def orphan(pixel, p, ctx, bit_depth):
        return pixel
    with pytest.raises(KeyError, match="context vocabulary does not declare"):
        orphan.run(np.zeros((2, 2), dtype=np.int64), bit_depth=8)


def test_a_variant_is_cached_and_refuses_what_is_not_configurable():
    wide = offset.configure({"offset": {"bits": 12}})
    assert wide is offset.configure({"offset": {"bits": 12}})
    assert wide.params.params[0].bits == 12
    assert wide.vocabulary is VOCABULARY
    with pytest.raises(ValueError, match="does not allow overriding"):
        offset.configure({"offset": {"frac": 2}})


def test_generated_verilog_carries_the_models_licence():
    core = offset.generate(StreamSpec(bit_depth=8), 8, 4, "offset_core")
    head = core.verilog.splitlines()[:4]
    assert head[0] == "// Copyright 2026 Serge Rabyking"
    assert head[1] == "// SPDX-License-Identifier: MIT"
    assert "// Generated by np2hw from offset() in test_blocks.py." in \
        core.verilog
    assert "module offset_core" in core.verilog


def test_blocks_are_discovered_in_a_package(tmp_path, monkeypatch):
    pkg = tmp_path / "discolib"
    pkg.mkdir()
    (pkg / "__init__.py").write_text("")
    (pkg / "inc.py").write_text(
        "from np2hw.blocks import StreamPort, block\n"
        "from np2hw.blocks.params import Param\n"
        "@block(version=(1, 0), description='increment',\n"
        "       inputs=(StreamPort('in'),), outputs=(StreamPort('out'),),\n"
        "       params=[Param('k', bits=4, description='step')])\n"
        "def inc(pixel, p, ctx, bit_depth):\n"
        "    return pixel + p.k\n")
    monkeypatch.syspath_prepend(str(tmp_path))
    assert set(registry("discolib")) == {"inc"}
    assert resolve("discolib", "inc").name == "inc"
    with pytest.raises(KeyError, match="declared blocks are"):
        resolve("discolib", "dec")


def test_the_model_sees_the_type_the_trace_gives_its_input():
    """An 8-bit stream is uint8 to the model, as it is to the trace, so a
    sum that does not widen wraps in the model exactly as in the hardware --
    whatever integer type the caller's frame arrived in."""
    frame = np.full((2, 2), 254, dtype=np.int64)
    out = offset.run(frame, {"offset": 3}, bit_depth=8)
    assert out.dtype == np.uint8
    assert (out == 1).all()                 # 257 wraps, as the RTL does
    wide = offset.run(frame, {"offset": 3}, bit_depth=10)
    assert wide.dtype == np.uint16 and (wide == 257).all()


@pytest.mark.skipif(__import__("shutil").which("verilator") is None,
                    reason="verilator not on PATH")
def test_the_model_and_its_rtl_agree_where_a_sum_wraps():
    import dataclasses

    from np2hw.design.composite import assemble
    from np2hw.pipeline import run as runner
    from toylib.blocks import offset as toy_offset
    # toylib's offset, less its saturation: a sum that wraps
    wrap = dataclasses.replace(toy_offset, model=lambda pixel, p, ctx,
                               bit_depth: pixel + p.offset)
    design = assemble("t", {"o": wrap}, [("in", "o.in"), ("o.out", "out")],
                      stream={"bits": 8, "max_width": 16, "max_height": 4})
    chain = runner.pixel_chain(design, "in", None)
    values = {"o": {"offset": 9}, "ctxblock": {}}
    frame = (np.arange(64).reshape(4, 16) + 220) % 256      # crosses 255
    model = runner.run_model(chain, frame, values, {}, 8)
    rtl = runner.run_rtl(chain, frame, values, {}, 8)
    assert np.array_equal(model, rtl)
    assert model.max() < 256


def test_a_frame_wider_than_its_stream_is_refused():
    """Values outside the told depth mean the caller and the stream disagree;
    cutting them down to fit would hide it."""
    with pytest.raises(ValueError, match="outside the 8-bit stream"):
        offset.run(np.full((2, 2), 300), {}, bit_depth=8)
    with pytest.raises(ValueError, match="outside the 8-bit stream"):
        offset.run(np.full((2, 2), -1), {}, bit_depth=8)


def test_a_multiply_is_built_as_the_device_times_it():
    """The timing model costs a multiply as the device's hard multiplier;
    left alone, synthesis builds a narrow one from LUTs, several times
    slower than the stage was scheduled for. So it is written as one."""
    from np2hw.timing import SERIES7
    from toylib.blocks import gain
    v = gain.generate(StreamSpec(bit_depth=8), 8, 4, "gain_core").verilog
    muls = [line for line in v.splitlines() if " * " in line]
    assert muls and all(line.strip().startswith(SERIES7.mul_attribute)
                        for line in muls)
    v = offset.generate(StreamSpec(bit_depth=8), 8, 4, "offset_core").verilog
    assert SERIES7.mul_attribute not in v


def test_a_device_must_say_how_its_multiplier_is_built():
    from np2hw.timing import Series7

    class Unstated(Series7):
        mul_attribute = None
    with pytest.raises(ValueError, match="mul_attribute"):
        Unstated()


from toylib.blocks import toyblock as libblock  # noqa: E402 (a runnable vocabulary)


@libblock(version=(1, 0), description="four times the pixel, clipped",
          inputs=(StreamPort("in"),), outputs=(StreamPort("out"),))
def quadruple(pixel, p, ctx, bit_depth):
    return saturate(pixel.astype(np.int32) * 4, bit_depth)


@libblock(version=(1, 0), description="minus four times the pixel, lifted",
          inputs=(StreamPort("in"),), outputs=(StreamPort("out"),))
def negquadruple(pixel, p, ctx, bit_depth):
    return saturate(pixel.astype(np.int32) * -4 + 1020, bit_depth)


@libblock(version=(1, 0), description="an edge, made non-linear: 4c - |w - e|",
          inputs=(StreamPort("in"),), outputs=(StreamPort("out"),))
def edge(pixel, p, ctx, bit_depth):
    height, width = pixel.shape[:2]
    x = np.pad(pixel.astype(np.int32), ((0, 0), (1, 1)), mode="edge")
    c, w, e = (x[:, 1 + d:1 + d + width] for d in (0, -1, 1))
    out = np.empty_like(c)
    # a value per site of the 2x2 tile, as a demosaic writes one
    est = saturate(4 * c - np.abs(w - e), bit_depth)
    out[0::2, 0::2] = est[0::2, 0::2]
    out[0::2, 1::2] = c[0::2, 1::2]
    out[1::2, 0::2] = c[1::2, 0::2]
    out[1::2, 1::2] = est[1::2, 1::2]
    return out


def _shifts_are_built_as_shifts(block):
    from np2hw.design.composite import assemble
    from np2hw.pipeline import run as runner
    from np2hw.timing import SERIES7
    v = block.generate(StreamSpec(bit_depth=8), 16, 4, "shift_core").verilog
    assert SERIES7.mul_attribute not in v      # no multiplier for a 2**k
    assert " * " not in v and "<<" in v
    design = assemble("t", {"b": block}, [("in", "b.in"), ("b.out", "out")],
                      stream={"bits": 8, "max_width": 16, "max_height": 4})
    chain = runner.pixel_chain(design, "in", None)
    frame = np.random.default_rng(3).integers(0, 256, (4, 16))
    values = {"b": {}, "ctxblock": {}}
    assert np.array_equal(runner.run_model(chain, frame, values, {}, 8),
                          runner.run_rtl(chain, frame, values, {}, 8))


@pytest.mark.skipif(__import__("shutil").which("verilator") is None,
                    reason="verilator not on PATH")
@pytest.mark.parametrize("block", [quadruple, negquadruple, edge],
                         ids=lambda b: b.name)
def test_a_multiply_by_a_power_of_two_is_a_shift(block):
    """Pointwise and in a window: no multiplier, and the RTL still the
    model's, word for word."""
    _shifts_are_built_as_shifts(block)


def test_the_schedule_times_a_shift_as_the_printer_builds_it():
    """A multiply by 2**k is built as a shift and costs a wire, by -2**k a
    shift and a negation, which costs an adder, by anything else the
    device's multiplier: the kinds lowering builds, costed as built."""
    import numpy as np
    from np2hw import Image2D, to_ir
    from np2hw.core.graph import walk
    from np2hw.core.pipeline import _cost
    from np2hw.timing import SERIES7 as dev

    def built(k):
        _, mod = to_ir(lambda img: img.astype(np.int32) * k,
                       Image2D("img", 8, 4, bits=8))
        values = list(mod.unit.roots.values()) + [
            o for r in mod.unit.regs for o in r.operands]
        return {n.kind: n for n in walk(values)}

    four, minus, three = built(4), built(-4), built(3)
    assert "hw.mul" not in four and _cost(four["hw.shl"], dev) == dev.wire()
    assert "hw.mul" not in minus and _cost(minus["hw.neg"], dev) == \
        dev.add(minus["hw.neg"].value.type.bits)
    assert _cost(three["hw.mul"], dev) == dev.mul()
