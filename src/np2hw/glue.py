"""Glue a design places between leaves: a concatenation of words.

A constant, a slice and an inverter are fixed modules (``np2hw/hdl``,
described in ``np2hw.hdl.glue``). A concatenation's ports are as many as
its words, each its own width, so that is what varies and what
:func:`concat` generates.
"""
from __future__ import annotations

from np2hw.ports import Pin, header, published


def concat(widths, interrupt: int = 0) -> dict:
    """Words side by side, ``in0`` in the low bits: a leaf a design names
    (``np2hw.glue:concat``) with each word's width, in order. With
    ``interrupt`` its output says it is interrupt lines, level high, its
    width stated -- what a processor's interrupt input is sized from where
    a tool sizes it by what drives it. Every port is published."""
    widths = [int(w) for w in widths]
    if not widths or min(widths) < 1:
        raise ValueError(f"a concatenation of {widths}: each word needs a "
                         "width of at least one")
    module = "np2hw_concat_" + "_".join(map(str, widths)) \
        + ("_irq" if interrupt else "")
    pins = [Pin(f"in{i}", "input", w) for i, w in enumerate(widths)]
    pins.append(Pin("q", "output", sum(widths), attribute=(
        '(* X_INTERFACE_INFO = "xilinx.com:signal:interrupt:1.0 q INTERRUPT", '
        'X_INTERFACE_PARAMETER = "SENSITIVITY LEVEL_HIGH, PortWidth '
        f'{sum(widths)}" *)') if interrupt else None))
    L = ["// Copyright 2026 Serge Rabyking",
         "// SPDX-License-Identifier: MIT",
         "//",
         f"// {module} -- words side by side, in0 in the low bits.",
         "// Generated by np2hw.glue.concat."]
    L += header(module, pins)
    L.append("    assign q = {" + ", ".join(
        f"in{i}" for i in reversed(range(len(widths)))) + "};")
    L.append("endmodule")
    return {"verilog": "\n".join(L) + "\n", "module": module,
            "interface": {"ports": published(pins)},
            # a word of its inputs' bits: a reset or a clock in it is theirs
            "facts": {"ancestry": {"q": [f"in{i}"
                                         for i in range(len(widths))]}}}


concat.leaf = True
