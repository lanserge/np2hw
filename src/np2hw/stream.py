"""Stream plumbing: the pieces that join generated cores to each other.

A core's timing claim is made about ITS OWN registers. That claim stays
true only while nothing else is on the path -- and a design is a
composition, so something always is. If a core's output is combinational,
every consumer inherits that depth before doing any work of its own, and
two modules that each meet timing alone can miss it together. This bench
saw exactly that twice, both times from `bayerlink_in`'s output (a 4:1
mux over its FIFO banks) into the first arithmetic of an ISP: -1.424ns on
one build and -1.792ns on another, from a receiver and a pipeline that
each passed on their own.

Nothing in a per-module model can catch it, and here the composing is
done by a block design np2hw never sees. So the fix is not a better
model: it is making the claim TRUE by construction, with a register at
the boundary.

`skid()` is that register. Registering a valid/ready interface naively
either drops backpressure or halves the throughput; a skid buffer holds
one extra beat so `ready` can be registered too, and the interface runs
at full rate with every signal leaving a flop.
"""
from __future__ import annotations


def skid(data_bits: int, module_name: str = "skid") -> dict:
    """A two-deep elastic register slice: every port leaves a flop.

    Args:
        data_bits: width of the payload carried through. Flags ride in
            it -- pack them alongside the data rather than adding ports,
            so one instance serves any stream shape.
        module_name: the emitted module's name.

    Returns:
        ``{"verilog", "module", "interface", "latency"}``. Latency is one
        cycle; throughput is one beat per cycle, unimpaired.
    """
    if data_bits < 1:
        raise ValueError(f"data_bits {data_bits} must be at least 1")

    L = []
    a = L.append
    a("// generated by np2hw -- elastic register slice (skid buffer).")
    a("//")
    a("// WHY, since a wire would be shorter: a core's timing claim is")
    a("// about its own registers, and stays true only while nothing else")
    a("// shares the path. A combinational output hands its depth to every")
    a("// consumer, so two modules that each meet timing alone can miss it")
    a("// together -- and no per-module model can see that coming.")
    a("//")
    a("// The skid register is what lets `ready` be registered too. Register")
    a("// a valid/ready interface with one flop and you either combinationally")
    a("// pass `ready` back (the path you were trying to break) or stall every")
    a("// other cycle. Holding one beat in reserve costs a register and buys")
    a("// full throughput with nothing combinational in either direction.")
    a(f"module {module_name} #(")
    a(f"    parameter W = {data_bits}")
    a(") (")
    a("    input  wire         clk,")
    a("    input  wire         rst,")
    a("    input  wire [W-1:0] s_data,")
    a("    input  wire         s_valid,")
    a("    output wire         s_ready,")
    a("    output wire [W-1:0] m_data,")
    a("    output wire         m_valid,")
    a("    input  wire         m_ready")
    a(");")
    a("    reg [W-1:0] out_data;")
    a("    reg         out_valid;")
    a("    reg [W-1:0] skid_data;   // the beat accepted while the sink")
    a("    reg         skid_valid;  // was busy; there is never more than one")
    a("")
    a("    // Accept whenever the reserve slot is free. This is a register")
    a("    // output, so the backward path is broken as well as the forward")
    a("    // one -- which is the half people forget.")
    a("    assign s_ready = !skid_valid;")
    a("    assign m_data  = out_data;")
    a("    assign m_valid = out_valid;")
    a("")
    a("    always @(posedge clk) begin")
    a("        if (rst) begin")
    a("            out_valid  <= 1'b0;")
    a("            skid_valid <= 1'b0;")
    a("        end else if (!skid_valid) begin")
    a("            if (out_valid && !m_ready) begin")
    a("                // The sink is busy and the source is offering: take")
    a("                // it into the reserve rather than refusing it.")
    a("                if (s_valid) begin")
    a("                    skid_data  <= s_data;")
    a("                    skid_valid <= 1'b1;")
    a("                end")
    a("            end else begin")
    a("                out_data  <= s_data;")
    a("                out_valid <= s_valid;")
    a("            end")
    a("        end else if (m_ready) begin")
    a("            // Draining the reserve. s_ready is low this cycle, so")
    a("            // nothing arrives to overwrite it.")
    a("            out_data   <= skid_data;")
    a("            out_valid  <= 1'b1;")
    a("            skid_valid <= 1'b0;")
    a("        end")
    a("    end")
    a("endmodule")

    return {
        "verilog": "\n".join(L),
        "module": module_name,
        "latency": 1,
        "interface": {
            "clock": "clk", "reset": "rst", "param_prefix": "param_",
            "input": {"prefix": "s", "data_bits": data_bits, "flags": ()},
            "output": {"prefix": "m", "data_bits": data_bits, "flags": ()},
            "streams": [
                {"prefix": "s", "direction": "in", "data_bits": data_bits,
                 "flags": (), "domain": ""},
                {"prefix": "m", "direction": "out", "data_bits": data_bits,
                 "flags": (), "domain": ""},
            ],
            "params": [],
            # The claim this module exists to make.
            "output_registered": True,
        },
    }
