"""Read a framebuffer out of memory, as the raster asks for it.

A display and a camera keep unrelated time, so a frame of memory sits
between them. Something has to fetch it back at the raster's pace, and a
vendor DMA does that job while making one thing impossible: knowing WHEN
its first beat arrives relative to the raster's first pixel. That offset
lands wherever it lands each time the link locks -- measured on one bench
at 0, 16, 48 and 80 pixels across reloads of an unchanged bitstream --
and a picture shifted by a random amount every time a cable is replugged
is not a picture that recovers by itself.

This engine cannot have that offset, by construction rather than by
correction. It owns the addressing, so its first beat IS the frame's
first pixel, and it says so on `tuser`. There is no start-address knob to
tune because there is no phase to get wrong.

  ADDRESSES COME FROM THE STREAM, not from software. base, bytes per
      line, lines and stride are ports. A source whose geometry changes
      moves them and the next frame is already right, which is what a
      sensor swapped at run time needs. Three register writes by a host
      that has to notice first is the thing this replaces.

  BURSTS NEVER CROSS 4K. AXI forbids it, and a burst that does is a
      protocol violation the interconnect is entitled to mangle rather
      than report. Each burst is trimmed to the shorter of the line's
      remainder and the distance to the next 4K boundary.

  BACKPRESSURE IS THE RASTER'S. Reads are issued only while the FIFO has
      room for a whole burst in flight, so `rready` is never withdrawn
      mid-burst -- an AXI read cannot be paused politely, and a slave
      left holding data is a slave that stalls the interconnect.
"""
from __future__ import annotations


def framebuffer_read(data_bits: int = 32,
                     clk_hz: int = 0,
                     addr_bits: int = 32,
                     burst_len: int = 16,
                     fifo_depth: int = 512,
                     module_name: str = "framebuffer_read") -> dict:
    """Emit an AXI4 read master that feeds a raster.

    Args:
        data_bits: width of the memory port AND of the emitted stream.
            One width, because a converter between them would be a
            second place for the pixel format to be described.
        addr_bits: address width of the memory port.
        burst_len: beats per burst, 1..256. Longer amortises the address
            phase; shorter needs less FIFO to keep a burst in flight.
        clk_hz: the clock this runs at, declared on the interface. Zero
            leaves it unstated, which a block design will accept and then
            make its clock-domain decisions blind -- an AXI master whose
            frequency is unknown is one the automation cannot size a
            converter for. State it.
        fifo_depth: beats of prefetch, a power of two, at least four
            bursts. This is the whole tolerance for DDR latency and for
            other masters holding the interconnect, so it is the knob
            that decides whether a busy bus shows on the screen.

    Returns:
        ``{"verilog", "module", "interface", ...}``. The stream side is
        `tdata/tvalid/tready/tuser/tlast` with `tuser` on the first beat
        of a frame and `tlast` on the last of each line -- what a raster
        generated by `scanout()` consumes.
    """
    if data_bits % 8 or not 8 <= data_bits <= 1024:
        raise ValueError(f"data_bits {data_bits} must be a byte multiple, 8..1024")
    if not 1 <= burst_len <= 256:
        raise ValueError(f"burst_len {burst_len} outside AXI's 1..256")
    if fifo_depth & (fifo_depth - 1) or fifo_depth < 4 * burst_len:
        raise ValueError(
            f"fifo_depth {fifo_depth} must be a power of two and hold at "
            f"least four bursts of {burst_len} -- less than that and the "
            "engine spends its time waiting to be allowed to ask")

    bytes_per_beat = data_bits // 8
    size_code = (bytes_per_beat.bit_length() - 1)     # AXI ARSIZE
    fptr = max(1, (fifo_depth - 1).bit_length())
    fcnt = max(1, fifo_depth.bit_length())

    L = []
    a = L.append
    a("// generated by np2hw -- framebuffer read engine: AXI4 master in,")
    a(f"// one {data_bits}-bit beat per clock out, {burst_len}-beat bursts,")
    a(f"// {fifo_depth} beats of prefetch. Addresses come from the ports,")
    a("// so the first beat emitted IS the frame's first pixel and says so")
    a("// on tuser: there is no start offset to measure or correct.")
    a(f"module {module_name} (")
    freq = f", FREQ_HZ {clk_hz}" if clk_hz else ""
    a(f'    (* X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF m_axi:m_axis{freq}" *)')
    a('    (* X_INTERFACE_INFO = "xilinx.com:signal:clock:1.0 clk CLK" *)')
    a("    input  wire        clk,")
    a('    (* X_INTERFACE_PARAMETER = "POLARITY ACTIVE_LOW" *)')
    a('    (* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 rst_n RST" *)')
    a("    input  wire        rst_n,   // AXI convention: active LOW")
    a("    // WHERE the frame is, and what shape. Ports, not registers:")
    a("    // a stream whose geometry changes moves these and the next")
    a("    // frame is already right. Sampled at each frame's start, so a")
    a("    // change lands on a boundary and never mid-picture.")
    a(f"    input  wire [{addr_bits-1}:0] base_addr,")
    a("    input  wire [15:0] line_beats,   // beats of PICTURE per line")
    a("    input  wire [15:0] lines,")
    a(f"    input  wire [{addr_bits-1}:0] stride_bytes, // line pitch in memory")
    a("    // Written from wherever software lives, which is not this")
    a("    // clock. ENABLE is synchronised because a single bit crossing")
    a("    // asynchronously is exactly what a synchroniser is for. The")
    a("    // geometry and the address are NOT, and must not be sampled")
    a("    // until after enable has risen: they are quasi-static by")
    a("    // contract -- write them, then enable -- so a synchroniser on")
    a("    // each would cost 80 flops to protect a value that is already")
    a("    // still. Enable rising is the handshake that says so.")
    a("    input  wire        enable,")
    a('    (* X_INTERFACE_PARAMETER = "READ_WRITE_MODE READ_ONLY" *)')
    a("    // AXI4 read address")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi ARID" *)')
    a("    output reg  [3:0]  m_axi_arid,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi ARADDR" *)')
    a(f"    output reg  [{addr_bits-1}:0] m_axi_araddr,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi ARLEN" *)')
    a("    output reg  [7:0]  m_axi_arlen,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi ARSIZE" *)')
    a("    output wire [2:0]  m_axi_arsize,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi ARBURST" *)')
    a("    output wire [1:0]  m_axi_arburst,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi ARCACHE" *)')
    a("    output wire [3:0]  m_axi_arcache,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi ARPROT" *)')
    a("    output wire [2:0]  m_axi_arprot,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi ARVALID" *)')
    a("    output reg         m_axi_arvalid,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi ARREADY" *)')
    a("    input  wire        m_axi_arready,")
    a("    // AXI4 read data")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi RDATA" *)')
    a(f"    input  wire [{data_bits-1}:0] m_axi_rdata,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi RRESP" *)')
    a("    input  wire [1:0]  m_axi_rresp,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi RLAST" *)')
    a("    input  wire        m_axi_rlast,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi RVALID" *)')
    a("    input  wire        m_axi_rvalid,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 m_axi RREADY" *)')
    a("    output wire        m_axi_rready,")
    a("    // the raster's stream")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:axis:1.0 m_axis TDATA" *)')
    a(f"    output wire [{data_bits-1}:0] m_axis_tdata,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:axis:1.0 m_axis TVALID" *)')
    a("    output wire        m_axis_tvalid,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:axis:1.0 m_axis TREADY" *)')
    a("    input  wire        m_axis_tready,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:axis:1.0 m_axis TUSER" *)')
    a("    output wire        m_axis_tuser,   // first beat of a frame")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:axis:1.0 m_axis TLAST" *)')
    a("    output wire        m_axis_tlast,   // last beat of a line")
    a("    // STICKY until reset, because a fetch that silently fell")
    a("    // behind is a picture nobody can explain later.")
    a("    output reg         underflow,      // the raster asked, we had none")
    a("    output reg         slverr,")
    a("    // WHY it is doing nothing, which a sticky error bit cannot")
    a("    // say. Held in reset, never enabled, and asking a bus that")
    a("    // never answers all look identical from outside: no data, no")
    a("    // error. One bit each and they stop looking identical.")
    a("    output wire [7:0]  dbg")
    a(");")
    a("    // One name for it inside, so the logic reads the way it did")
    a("    // before the port took the bus's convention.")
    a("    wire rst = ~rst_n;")
    a(f"    localparam integer BEAT_BYTES = {bytes_per_beat};")
    a(f"    localparam integer BURST      = {burst_len};")
    a("")
    a(f"    assign m_axi_arsize  = 3'd{size_code};")
    a("    assign m_axi_arburst = 2'b01;            // INCR")
    a("    assign m_axi_arcache = 4'b0011;          // bufferable, modifiable")
    a("    assign m_axi_arprot  = 3'b000;")
    a("")
    a("    // ---- geometry, sampled at a frame boundary --------------------")
    a(f"    reg [{addr_bits-1}:0] f_base, f_stride;")
    a("    reg [15:0] f_line_beats, f_lines;")
    a("")
    a("    // ---- the ASK side: where the next burst comes from ------------")
    a(f"    reg [{addr_bits-1}:0] line_addr;   // start of the line being read")
    a("    reg [15:0] beats_left;             // of this line, still to ask for")
    a("    reg [15:0] line_no;")
    a(f"    reg [{addr_bits-1}:0] ask_addr;")
    a("    reg        running;")
    a("    // The burst decision, REGISTERED: to_4k's subtract, the")
    a("    // shift, two compares and the min were one combinational")
    a("    // cone into araddr/arlen -- the WNS of this engine's first")
    a("    // hardware build (-0.344 at 148.5 MHz, every worst path")
    a("    // inside it). One burst per 16 beats means the extra cycle")
    a("    // is free; the prefetch FIFO never notices.")
    a("    reg [15:0] burst_r;")
    a("    reg        burst_ok;")
    a("    reg        acct_err;   // sticky: the books tried to go negative")
    a("    // Per-burst length audit: the lengths ISSUED ride a small")
    a("    // FIFO; every RLAST closes one and the beat count must")
    a("    // equal it. 'short' and 'long' are different diseases and")
    a("    // get different sticky bits -- one register read names the")
    a("    // violation shape instead of an evening of forensics.")
    a("    wire [7:0] this_burst_len_dbg = burst_r[7:0] - 8'd1;")
    a("    reg [7:0] lq [0:31];   // depth 32: outstanding bursts can")
    a("    reg [4:0] lq_w, lq_r;  // reach room/burst_len -- an 8-deep")
    a("                           // queue lied SHORT within a minute")
    a("    reg [8:0] rcv_beats;")
    a("    reg burst_short, burst_long;")
    a("")
    a("    // A burst may not cross a 4K boundary: AXI forbids it, and the")
    a("    // interconnect is entitled to mangle one that does rather than")
    a("    // say so. Room is the distance to the next boundary, in beats.")
    a("    wire [12:0] to_4k   = 13'd4096 - {1'b0, ask_addr[11:0]};")
    a("    wire [15:0] room_4k = to_4k / BEAT_BYTES;")
    a("    wire [15:0] want    = (beats_left < BURST[15:0]) ? beats_left")
    a("                                                     : BURST[15:0];")
    a("    wire [15:0] this_burst = (want < room_4k) ? want : room_4k;")
    a("")
    a("    // ---- the prefetch FIFO ----------------------------------------")
    a(f"    reg [{data_bits+1}:0] fifo [0:{fifo_depth-1}];   // {{last, user, data}}")
    a(f"    reg [{fptr-1}:0] wr, rd;")
    a(f"    reg [{fcnt-1}:0] count;")
    a(f"    reg [{fcnt-1}:0] inflight;   // beats asked for, not yet arrived")
    a("")
    a("    // Ask only when a WHOLE burst can land, so rready is never")
    a("    // withdrawn part way through one. An AXI read cannot be paused")
    a("    // politely; a slave left holding data stalls the interconnect.")
    a(f"    wire [{fcnt-1}:0] committed = count + inflight;")
    a(f"    wire room_for_burst = (committed + BURST[{fcnt-1}:0]) <= "
      f"{fcnt}'d{fifo_depth};")
    a("")
    a("    // burst_r==0 must never reach the bus: arlen would wrap to")
    a("    // 255 -- a 256-beat burst nobody accounted for, crossing 4K,")
    a("    // rotating every counter downstream of it. Guarded HERE,")
    a("    // whatever path might produce the zero.")
    a("    wire do_issue = running && burst_ok && (burst_r != 16'd0)")
    a("                 && !m_axi_arvalid")
    a("                 && room_for_burst && (beats_left != 16'd0);")
    a("    assign m_axi_rready = 1'b1;   // guaranteed by room_for_burst")
    a("")
    a("    // ---- the EMIT side --------------------------------------------")
    a(f"    wire [{data_bits+1}:0] head = fifo[rd];")
    a("    assign m_axis_tvalid = (count != 0);")
    a(f"    assign m_axis_tdata  = head[{data_bits-1}:0];")
    a(f"    assign m_axis_tuser  = head[{data_bits}];")
    a(f"    assign m_axis_tlast  = head[{data_bits+1}];")
    a("    wire pop  = m_axis_tvalid && m_axis_tready;")
    a("    wire push = m_axi_rvalid && m_axi_rready;")
    a("")
    a("    // Which beat of the FRAME is arriving. Asks run ahead of")
    a("    // arrivals -- that is the point of prefetch -- so the flags")
    a("    // cannot be decided where the asking happens: at the moment the")
    a("    // last line is requested, beats of the previous frame are still")
    a("    // in the air. This counter follows the DATA.")
    a("    reg [15:0] got_in_line, got_line;")
    a("    wire beat_is_eol   = (got_in_line == f_line_beats - 16'd1);")
    a("    wire beat_is_first = (got_in_line == 16'd0) && (got_line == 16'd0);")
    a("    wire beat_is_last_line = (got_line == f_lines - 16'd1);")
    a("")
    a("    reg ever_started;")
    a("    (* ASYNC_REG = \"TRUE\" *) reg en0 = 1'b0, en1 = 1'b0;")
    a("    reg en2 = 1'b0;")
    a("    always @(posedge clk) begin")
    a("        en0 <= enable;")
    a("        en1 <= en0;")
    a("        en2 <= en1;")
    a("    end")
    a("    // Enable RISING is a clean start -- but a DRAINED one. AXI")
    a("    // reads cannot be cancelled, so a reset that wipes the books")
    a("    // while bursts are in flight turns their beats into orphans")
    a("    // that corrupt the fresh books: the first heal design did")
    a("    // exactly that and re-infected the engine every lap. So the")
    a("    // rise arms HEALING: asks stop, in-flight beats land and")
    a("    // drain the count, and only at inflight==0 do the pointers")
    a("    // clear and the stickies re-arm.")
    a("    wire en_rise = en1 && !en2;")
    a("    reg healing;")
    a("    always @(posedge clk) begin")
    a("        if (rst) begin")
    a("            running <= 1'b0; m_axi_arvalid <= 1'b0; m_axi_arid <= 4'd0;")
    a("            m_axi_araddr <= 0; m_axi_arlen <= 8'd0;")
    a("            line_addr <= 0; ask_addr <= 0; beats_left <= 0; line_no <= 0;")
    a("            wr <= 0; rd <= 0; count <= 0; inflight <= 0;")
    a("            got_in_line <= 0; got_line <= 0;")
    a("            underflow <= 1'b0; slverr <= 1'b0; ever_started <= 1'b0;")
    a("            burst_r <= 16'd0; burst_ok <= 1'b0; acct_err <= 1'b0;")
    a("            healing <= 1'b0;")
    a("            lq_w <= 0; lq_r <= 0; rcv_beats <= 0;")
    a("            burst_short <= 0; burst_long <= 0;")
    a("            f_base <= 0; f_stride <= 0; f_line_beats <= 0; f_lines <= 0;")
    a("        end else if (en_rise || healing) begin")
    a("            running <= 1'b0;")
    a("            if (m_axi_arvalid && m_axi_arready) m_axi_arvalid <= 0;")
    a("            healing <= 1'b1;")
    a("            if (!m_axi_arvalid && inflight == 0) begin")
    a("                wr <= 0; rd <= 0; count <= 0;")
    a("                got_in_line <= 0; got_line <= 0;")
    a("                burst_r <= 16'd0; burst_ok <= 1'b0;")
    a("                lq_w <= 0; lq_r <= 0; rcv_beats <= 0;")
    a("                acct_err <= 0; burst_short <= 0; burst_long <= 0;")
    a("                underflow <= 0; slverr <= 0;")
    a("                healing <= 1'b0;")
    a("            end")
    a("            inflight <= inflight - ((push && inflight != 0)")
    a("                                    ? 16'd1 : 16'd0);")
    a("        end else begin")
    a("            // START, or restart at a frame boundary. Geometry is")
    a("            // sampled here and nowhere else.")
    a("            if (!running && en1) begin")
    a("                f_base <= base_addr; f_stride <= stride_bytes;")
    a("                f_line_beats <= line_beats; f_lines <= lines;")
    a("                line_addr <= base_addr; ask_addr <= base_addr;")
    a("                beats_left <= line_beats; line_no <= 16'd0;")
    a("                // NOT the arrival counters: this restart happens")
    a("                // when the last line is ASKED for, and the tail of")
    a("                // the frame is still in the air. They wrap on their")
    a("                // own, where the data is.")
    a("                running <= (line_beats != 0) && (lines != 0);")
    a("                burst_ok <= 1'b0;")
    a("            end")
    a("")
    a("            // the calc cycle: valid until anything it derives")
    a("            // from moves (issue, line step, restart -- each of")
    a("            // which clears burst_ok AFTER this line, and last")
    a("            // assignment wins)")
    a("            if (running && !burst_ok) begin")
    a("                burst_r <= this_burst;")
    a("                burst_ok <= 1'b1;")
    a("            end")
    a("")
    a("            // ---- issue -------------------------------------------")
    a("            if (m_axi_arvalid && m_axi_arready) begin")
    a("                m_axi_arvalid <= 1'b0;")
    a("            end else if (do_issue) begin")
    a("                m_axi_araddr  <= ask_addr;")
    a("                m_axi_arlen   <= burst_r[7:0] - 8'd1;")
    a("                // audited copy of the length just issued")
    a("                m_axi_arvalid <= 1'b1;")
    a("                ask_addr      <= ask_addr + (burst_r * BEAT_BYTES);")
    a("                beats_left    <= beats_left - burst_r;")
    a("                burst_ok      <= 1'b0;")
    a("            end")
    a("            // ONE place: a burst commits when it is issued, a beat")
    a("            // uncommits when it lands, and both can happen at once.")
    a("            inflight <= inflight + (do_issue ? burst_r : 16'd0)")
    a("                                 - ((push && inflight != 0) ? 16'd1")
    a("                                                            : 16'd0);")
    a("            // an arrival nobody asked for: the books CANNOT go")
    a("            // negative silently -- latch the violation instead.")
    a("            if (push && inflight == 0 && !do_issue) acct_err <= 1'b1;")
    a("            if (do_issue) begin")
    a("                lq[lq_w] <= this_burst_len_dbg;")
    a("                lq_w <= lq_w + 5'd1;")
    a("            end")
    a("            if (push) begin")
    a("                if (m_axi_rlast) begin")
    a("                    if (rcv_beats + 9'd1 < {1'b0, lq[lq_r]} + 9'd1)")
    a("                        burst_short <= 1'b1;")
    a("                    if (rcv_beats + 9'd1 > {1'b0, lq[lq_r]} + 9'd1)")
    a("                        burst_long <= 1'b1;")
    a("                    lq_r <= lq_r + 5'd1;")
    a("                    rcv_beats <= 9'd0;")
    a("                end else begin")
    a("                    rcv_beats <= rcv_beats + 9'd1;")
    a("                    if (rcv_beats + 9'd1 > {1'b0, lq[lq_r]} + 9'd1)")
    a("                        burst_long <= 1'b1;")
    a("                end")
    a("            end")
    a("")
    a("            // A line finished being ASKED for: step to the next, by")
    a("            // stride rather than by where the last burst ended --")
    a("            // the picture is a window in a wider frame.")
    a("            if (running && beats_left == 0 && !m_axi_arvalid) begin")
    a("                if (line_no == f_lines - 16'd1) begin")
    a("                    running   <= 1'b0;     // frame asked for; go again")
    a("                end else begin")
    a("                    line_no    <= line_no + 16'd1;")
    a("                    line_addr  <= line_addr + f_stride;")
    a("                    ask_addr   <= line_addr + f_stride;")
    a("                    beats_left <= f_line_beats;")
    a("                    burst_ok   <= 1'b0;")
    a("                end")
    a("            end")
    a("")
    a("            // ---- arrive ------------------------------------------")
    a("            if (push) begin")
    a("                fifo[wr] <= {beat_is_eol, beat_is_first, m_axi_rdata};")
    a("                wr <= wr + 1'b1;")
    a("                if (beat_is_eol) begin")
    a("                    got_in_line <= 16'd0;")
    a("                    got_line <= beat_is_last_line ? 16'd0")
    a("                                                  : got_line + 16'd1;")
    a("                end else begin")
    a("                    got_in_line <= got_in_line + 16'd1;")
    a("                end")
    a("                if (m_axi_rresp[1]) slverr <= 1'b1;")
    a("            end")
    a("            if (pop) rd <= rd + 1'b1;")
    a("            case ({push, pop})")
    a("                2'b10: count <= count + 1'b1;")
    a("                2'b01: count <= count - 1'b1;")
    a("                default: ;")
    a("            endcase")
    a("")
    a("            // The raster asked and there was nothing. Sticky: a fetch")
    a("            // that fell behind once explains a tear nobody else can.")
    a("            if (m_axis_tready && !m_axis_tvalid && ever_started)")
    a("                underflow <= 1'b1;")
    a("            if (push) ever_started <= 1'b1;")
    a("        end")
    a("    end")
    a("    // The five dbg bits that SURVIVE the status word (the top")
    a("    // three are truncated by the 35-into-32 concat -- learned")
    a("    // by losing an instrument to it): a ticking SOF pulse")
    a("    // (frame cadence = flags alive), a live STALLED flag (the")
    a("    // ask path is blocked right now and says so), the sticky")
    a("    // accounting violation, enable and running.")
    a("    reg sof_tick;")
    a("    always @(posedge clk)")
    a("        if (rst) sof_tick <= 0;")
    a(f"        else if (pop && head[{data_bits}]) sof_tick <= ~sof_tick;")
    a("    // registered: dbg must leave flops like every other output")
    a("    // -- the boundary suite caught the wire version same-day.")
    a("    reg stalled;")
    a("    always @(posedge clk)")
    a("        stalled <= running && (!room_for_burst || !burst_ok);")
    a("    // ORDER MATTERS: only [4:0] survive the status concat's")
    a("    // 35-into-32 truncation, so the VERDICT bits ride low:")
    a("    // [4] long  [3] stalled (the heal trigger)  [2] short")
    a("    // [1] acct  [0] running. sof/en/started ride the top and")
    a("    // are visible only to an ILA.")
    a("    assign dbg = {sof_tick, ever_started, en1,")
    a("                  burst_long, stalled, burst_short,")
    a("                  acct_err, running};")
    a("endmodule")

