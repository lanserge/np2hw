"""The DDC slave: a register file reachable over the display cable.

An HDMI link already carries an I2C bus -- DDC, the wires a source uses
to read its sink's EDID. A receiver that answers on that bus turns the
one cable into the control plane: the source can identify the sink
(EDID, the standard address) and read or write the ISP's registers (a
second address on the same wires), with no network and no CPU on the
board. Parameters keep their whole existing contract -- the file, the
commit bit, the travelling wave -- because this block is just another
bus master; it translates, it does not own.

Two personalities, one engine:

  EDID      a read-only ROM at the standard address. This is what makes
            a source believe a display is present at all, so it is not
            an accessory -- it is the handshake. The bytes are the
            caller's (a valid EDID whose vendor block can carry the
            receiver's identity); this module only insists the
            checksums hold, because a malformed EDID is a board that
            silently stops being detected.

  REGISTERS a 16-bit register address, 32-bit big-endian data, with
            auto-increment for bursts, bridged to an AXI-lite master.
            A refused write (the file is armed, mid-wave) comes back
            SLVERR and is answered with NACK: the refusal contract
            survives translation onto the cable's bus.

Clock discipline: everything runs on the BOARD clock; SCL and SDA are
oversampled through two flops and a majority filter. The cable
contributes voltage levels, never a clock -- the rule every addressable
thing on this bench obeys. SDA is open-drain by construction: the one
output is `sda_pull` (drive low), and no code path can drive the line
high. No clock stretching: at board rates against I2C's 400 kHz, an
AXI round trip to an always-answering register file fits inside a
half-bit hundreds of times over -- the ack window simply reports what
the bus answered, and an answer that somehow misses the window becomes
a NACK, never a wrong ack.
"""
from __future__ import annotations


def ddc_slave(reg_addr7: int = 0x37,
              edid: bytes | None = None,
              edid_addr7: int = 0x50,
              addr_bits: int = 16,
              module_name: str = "ddc_slave") -> dict:
    """Emit the DDC slave.

    Args:
        reg_addr7: 7-bit bus address of the register personality.
        edid: optional EDID content, 128 or 256 bytes, each 128-byte
            block summing to 0 mod 256 -- validated here, refused
            otherwise, because the failure mode of a bad EDID is a
            sink that quietly stops existing.
        edid_addr7: 7-bit bus address of the EDID personality (0x50 is
            the address every source already reads).
        addr_bits: width of the register (byte) address space.
        module_name: emitted module name.
    """
    if not 0 <= reg_addr7 <= 0x7F:
        raise ValueError(f"reg_addr7 {reg_addr7:#x} is not a 7-bit address")
    have_edid = edid is not None
    if have_edid:
        if len(edid) not in (128, 256):
            raise ValueError(f"EDID must be 128 or 256 bytes, got {len(edid)}")
        for blk in range(0, len(edid), 128):
            if sum(edid[blk:blk + 128]) % 256 != 0:
                raise ValueError(
                    f"EDID block at {blk} fails its checksum -- a source "
                    "shown this stops detecting the sink; refused here, "
                    "not debugged on a bench")
        if not 0 <= edid_addr7 <= 0x7F or edid_addr7 == reg_addr7:
            raise ValueError("edid_addr7 must be a distinct 7-bit address")
        eidx = "eoff[6:0]" if len(edid) == 128 else "eoff"
    AW = addr_bits

    L = []
    a = L.append
    a("// generated by np2hw -- DDC slave: registers over the display")
    a("// cable. Board-clocked and oversampled; the cable contributes")
    a("// levels, never a clock. SDA is open-drain BY CONSTRUCTION:")
    a("// the only output is sda_pull, so no path can drive the line")
    a("// high. A SLVERR from the fabric becomes a NACK on the bus --")
    a("// the register file's refusal contract, translated.")
    a(f"module {module_name} #(")
    a(f"    parameter AW = {AW}")
    a(") (")
    a('    (* X_INTERFACE_INFO = "xilinx.com:signal:clock:1.0 clk CLK", '
      'X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF M_AXI, '
      'ASSOCIATED_RESET rst" *)')
    a("    input  wire clk,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 rst RST", '
      'X_INTERFACE_PARAMETER = "POLARITY ACTIVE_HIGH" *)')
    a("    input  wire rst,")
    a("    input  wire scl_i,")
    a("    input  wire sda_i,")
    a("    output wire sda_pull,")
    a("    // AXI-lite master: the register file's language. The")
    a("    // X_INTERFACE_INFO lines are the same lesson as reset")
    a("    // polarity: DECLARE at the owner what a block design")
    a("    // would otherwise guess.")
    m = "xilinx.com:interface:aximm:1.0 M_AXI"
    for attr, decl in [
        (f"{m} AWADDR",  "output reg  [AW-1:0] m_awaddr,"),
        (f"{m} AWVALID", "output reg           m_awvalid,"),
        (f"{m} AWREADY", "input  wire          m_awready,"),
        (f"{m} WDATA",   "output reg  [31:0]   m_wdata,"),
        (f"{m} WVALID",  "output reg           m_wvalid,"),
        (f"{m} WREADY",  "input  wire          m_wready,"),
        (f"{m} WSTRB",   "output wire [3:0]    m_wstrb,"),
        (f"{m} BRESP",   "input  wire [1:0]    m_bresp,"),
        (f"{m} BVALID",  "input  wire          m_bvalid,"),
        (f"{m} BREADY",  "output wire          m_bready,"),
        (f"{m} ARADDR",  "output reg  [AW-1:0] m_araddr,"),
        (f"{m} ARVALID", "output reg           m_arvalid,"),
        (f"{m} ARREADY", "input  wire          m_arready,"),
        (f"{m} RDATA",   "input  wire [31:0]   m_rdata,"),
        (f"{m} RRESP",   "input  wire [1:0]    m_rresp,"),
        (f"{m} RVALID",  "input  wire          m_rvalid,"),
        (f"{m} RREADY",  "output wire          m_rready"),
    ]:
        a(f'    (* X_INTERFACE_INFO = "{attr}" *)')
        a(f"    {decl}")
    a(");")
    a("    assign m_wstrb  = 4'hF;")
    a("    assign m_bready = 1'b1;")
    a("    assign m_rready = 1'b1;")
    a("")
    a("    // ---- the pins, tamed: two flops then a majority of three,")
    a("    // so a glitch shorter than two board clocks never reaches")
    a("    // the engine. Everything after this line is synchronous.")
    a("    reg [2:0] scl_h, sda_h;")
    a("    always @(posedge clk) begin")
    a("        scl_h <= {scl_h[1:0], scl_i};")
    a("        sda_h <= {sda_h[1:0], sda_i};")
    a("    end")
    a("    wire scl_f = (scl_h[2] & scl_h[1]) | (scl_h[1] & scl_h[0])")
    a("               | (scl_h[2] & scl_h[0]);")
    a("    wire sda_f = (sda_h[2] & sda_h[1]) | (sda_h[1] & sda_h[0])")
    a("               | (sda_h[2] & sda_h[0]);")
    a("    reg scl_q, sda_q;")
    a("    always @(posedge clk) begin scl_q <= scl_f; sda_q <= sda_f; end")
    a("    wire scl_rise = scl_f & ~scl_q;")
    a("    wire scl_fall = ~scl_f & scl_q;")
    a("    // START and STOP are the two things allowed to move SDA")
    a("    // while SCL is high; both are commands, not data.")
    a("    wire start_c = scl_f & scl_q & sda_q & ~sda_f;")
    a("    wire stop_c  = scl_f & scl_q & ~sda_q & sda_f;")
    a("")
    a("    localparam ST_IDLE  = 3'd0, ST_ADDR  = 3'd1, ST_REGHI = 3'd2,")
    a("               ST_REGLO = 3'd3, ST_WDATA = 3'd4, ST_RDATA = 3'd5,")
    a("               ST_EOFF  = 3'd6, ST_DEAD  = 3'd7;")
    a("    reg [2:0]  st;")
    a("    reg [3:0]  nbit;        // rises this byte: 0..7 data, 8 ack")
    a("    reg [7:0]  sh, txsh;")
    a("    reg        sel_edid, tx_active, txed_once;")
    a("    reg [1:0]  widx;")
    a("    reg [23:0] wbuf;")
    a("    reg [AW-1:0] raddr;")
    a("    reg [7:0]  eoff;")
    a("    // the ack window: pull SDA only when there is a yes to say.")
    a("    reg ack_win, ack_ok, tx_low, mack;")
    a("    assign sda_pull = (ack_win & ack_ok) | tx_low;")
    a("    wire [7:0] sh_next = {sh[6:0], sda_f};")
    a("")
    a("    // ---- AXI: single outstanding, always-accepting response")
    a("    // channels. wr_wait marks 'this ack window is waiting on a")
    a("    // bus answer' -- without it, every window with widx==0")
    a("    // would judge a response nobody asked for.")
    a("    reg wr_pend, rd_pend, wr_ok, wr_done, wr_wait;")
    a("    reg issue_wr, issue_rd;")
    a("    reg [31:0] wword, rword;")
    a("    reg [AW-1:0] rd_addr;")
    a("    always @(posedge clk) begin")
    a("        if (rst) begin")
    a("            m_awvalid <= 0; m_wvalid <= 0; m_arvalid <= 0;")
    a("            wr_pend <= 0; rd_pend <= 0; wr_ok <= 0; wr_done <= 0;")
    a("        end else begin")
    a("            wr_done <= 0;")
    a("            if (m_awvalid && m_awready) m_awvalid <= 0;")
    a("            if (m_wvalid  && m_wready)  m_wvalid  <= 0;")
    a("            if (m_arvalid && m_arready) m_arvalid <= 0;")
    a("            if (wr_pend && m_bvalid) begin")
    a("                wr_pend <= 0;")
    a("                wr_ok   <= (m_bresp == 2'b00);")
    a("                wr_done <= 1;   // one-shot: the verdict and its")
    a("                                // freshness land TOGETHER -- an")
    a("                                // ack gated on wr_ok alone reads")
    a("                                // the PREVIOUS word's success for")
    a("                                // one cycle and acks a refusal")
    a("            end")
    a("            if (rd_pend && m_rvalid) begin")
    a("                rd_pend <= 0;")
    a("                rword   <= m_rdata;")
    a("            end")
    a("            if (issue_wr) begin")
    a("                m_awaddr <= raddr;   m_awvalid <= 1;")
    a("                m_wdata  <= wword;   m_wvalid  <= 1;")
    a("                wr_pend  <= 1;       wr_ok     <= 0;")
    a("            end")
    a("            if (issue_rd) begin")
    a("                m_araddr <= rd_addr; m_arvalid <= 1;")
    a("                rd_pend  <= 1;")
    a("            end")
    a("        end")
    a("    end")
    if have_edid:
        a("")
        a(f"    // EDID: {len(edid)} bytes, read-only, checksummed at")
        a("    // generation time -- the calling card a source reads")
        a("    // before it agrees the sink exists.")
        a(f"    reg [7:0] rom [0:{len(edid) - 1}];")
        a("    initial begin")
        for i, b in enumerate(edid):
            a(f"        rom[{i}] = 8'h{b:02X};")
        a("    end")
    a("")
    a("    // the next byte a read transfer would send")
    a("    reg [7:0] tx_next;")
    a("    always @(*) begin")
    if have_edid:
        a(f"        if (sel_edid) tx_next = rom[{eidx}];")
        a("        else case (widx)")
    else:
        a("        case (widx)")
    a("            2'd0: tx_next = rword[31:24];")
    a("            2'd1: tx_next = rword[23:16];")
    a("            2'd2: tx_next = rword[15:8];")
    a("            default: tx_next = rword[7:0];")
    a("        endcase")
    a("    end")
    a("")
    a("    always @(posedge clk) begin")
    a("        issue_wr <= 0; issue_rd <= 0;")
    a("        if (rst) begin")
    a("            st <= ST_IDLE; nbit <= 0; ack_win <= 0; ack_ok <= 0;")
    a("            tx_low <= 0; tx_active <= 0; txed_once <= 0;")
    a("            widx <= 0; mack <= 0; wr_wait <= 0;")
    a("        end else if (start_c) begin")
    a("            // a start is also a repeated start: whatever was in")
    a("            // flight, the address byte comes next.")
    a("            st <= ST_ADDR; nbit <= 0; ack_win <= 0; ack_ok <= 0;")
    a("            tx_low <= 0; tx_active <= 0; txed_once <= 0;")
    a("            wr_wait <= 0;")
    a("        end else if (stop_c) begin")
    a("            st <= ST_IDLE; ack_win <= 0; ack_ok <= 0;")
    a("            tx_low <= 0; tx_active <= 0; txed_once <= 0;")
    a("            wr_wait <= 0;")
    a("        end else if (st != ST_IDLE) begin")
    a("            // a write's answer arrives mid-window: report it,")
    a("            // gated on the one-shot so only a FRESH yes counts")
    a("            if (wr_wait && wr_done && wr_ok) ack_ok <= 1;")
    a("            if (scl_rise) begin")
    a("                if (nbit <= 4'd7) begin")
    a("                    sh <= sh_next;")
    a("                    nbit <= nbit + 1;")
    a("                    if (nbit == 4'd7) begin")
    a("                        // byte complete: decide what the ack")
    a("                        // window (opening at the next fall)")
    a("                        // will report.")
    a("                        case (st)")
    a("                        ST_ADDR: begin")
    a(f"                            if (sh_next[7:1] == 7'h{reg_addr7:02X})"
      " begin")
    a("                                sel_edid <= 0;")
    a("                                ack_ok <= 1;")
    a("                                if (sh_next[0]) begin")
    a("                                    st <= ST_RDATA; widx <= 0;")
    a("                                    tx_active <= 1;")
    a("                                    issue_rd <= 1; rd_addr <= raddr;")
    a("                                end else st <= ST_REGHI;")
    a("                            end")
    if have_edid:
        a(f"                            else if (sh_next[7:1] == "
          f"7'h{edid_addr7:02X}) begin")
        a("                                sel_edid <= 1;")
        a("                                ack_ok <= 1;")
        a("                                if (sh_next[0]) begin")
        a("                                    st <= ST_RDATA;")
        a("                                    tx_active <= 1;")
        a("                                end else st <= ST_EOFF;")
        a("                            end")
    a("                            else begin")
    a("                                ack_ok <= 0; st <= ST_DEAD;")
    a("                            end")
    a("                        end")
    a("                        ST_REGHI: begin")
    a("                            raddr <= {sh_next[AW-9:0], raddr[7:0]};")
    a("                            ack_ok <= 1; st <= ST_REGLO;")
    a("                        end")
    a("                        ST_REGLO: begin")
    a("                            raddr[7:0] <= sh_next;")
    a("                            ack_ok <= 1; st <= ST_WDATA; widx <= 0;")
    a("                        end")
    a("                        ST_WDATA: begin")
    a("                            if (widx == 2'd3) begin")
    a("                                // last byte of the word: put it")
    a("                                // on the bus; the window reports")
    a("                                // the BUS's answer, not a hope.")
    a("                                wword <= {wbuf, sh_next};")
    a("                                issue_wr <= 1;")
    a("                                wr_wait <= 1;")
    a("                                ack_ok <= 0;")
    a("                            end else begin")
    a("                                wbuf <= {wbuf[15:0], sh_next};")
    a("                                ack_ok <= 1;")
    a("                            end")
    a("                            widx <= widx + 1;")
    a("                        end")
    a("                        ST_EOFF: begin")
    a("                            eoff <= sh_next; ack_ok <= 1;")
    a("                        end")
    a("                        default: ack_ok <= 0;")
    a("                        endcase")
    a("                    end")
    a("                end else begin")
    a("                    // the ack-slot rise: for bytes we sent,")
    a("                    // this is the master's verdict.")
    a("                    mack <= ~sda_f;")
    a("                    nbit <= 4'd9;")
    a("                end")
    a("            end")
    a("            if (scl_fall) begin")
    a("                if (nbit == 4'd8) begin")
    a("                    ack_win <= 1;      // low phase of the ack bit")
    a("                    tx_low <= 0;       // never drive during ack")
    a("                end else if (nbit == 4'd9) begin")
    a("                    ack_win <= 0; ack_ok <= 0; nbit <= 0;")
    a("                    if (wr_wait) begin")
    a("                        wr_wait <= 0;")
    a("                        if (wr_ok) raddr <= raddr + 4;")
    a("                        else st <= ST_DEAD;  // refused: NACKed")
    a("                    end")
    a("                    if (tx_active) begin")
    a("                        if (txed_once && !mack) begin")
    a("                            // master said enough")
    a("                            tx_active <= 0; tx_low <= 0;")
    a("                            st <= ST_DEAD;")
    a("                        end else begin")
    a("                            txsh <= tx_next;")
    a("                            tx_low <= ~tx_next[7];")
    a("                            txed_once <= 1;")
    if have_edid:
        a("                            if (sel_edid) eoff <= eoff + 1;")
    a("                            if (!sel_edid) begin")
    a("                                widx <= widx + 1;")
    a("                                if (widx == 2'd3) begin")
    a("                                    // word done: step and")
    a("                                    // prefetch the next")
    a("                                    raddr <= raddr + 4;")
    a("                                    issue_rd <= 1;")
    a("                                    rd_addr <= raddr + 4;")
    a("                                end")
    a("                            end")
    a("                        end")
    a("                    end")
    a("                end else if (tx_active && nbit != 4'd0) begin")
    a("                    // shift the next data bit onto the line")
    a("                    txsh <= {txsh[6:0], 1'b0};")
    a("                    tx_low <= ~txsh[6];")
    a("                end")
    a("            end")
    a("        end")
    a("    end")
    a("endmodule")

    return {
        "verilog": "\n".join(L),
        "module": module_name,
        "interface": {
            "clock": "clk", "reset": "rst",
            "reg_addr7": reg_addr7,
            "edid_addr7": edid_addr7 if have_edid else None,
        },
    }
