"""A loaded design built by Vivado from its own Verilog.

The design is written as Verilog, one module per composite
(:mod:`np2hw.design.verilog`), and Vivado makes only what is its own: each
vendor leaf as an IP by its cell's name, from its implementation's
settings, and -- for the leaves that exist only in Vivado's IP integrator
(a procedure, or an IP marked ``integrator``) -- one block design holding
them, wired among themselves as the design says, its ports to the rest of
the design named as the Verilog instances them. The top is the design's
own top module; nothing is decided here.

    tcl, files, facts = emit_rtl(design, out=..., part=..., ...)
"""
from __future__ import annotations

from pathlib import Path

from np2hw.design.composite import source_file
from np2hw.design.verilog import group_ports, modules
from np2hw.toolchain.vivado import EmitError, cell_names, tcl
from np2hw.toolchain.vivado.vendor_check import vendor, vendor_pins

AXIMM = "xilinx.com:interface:aximm_rtl:1.0"

# which AXI signal says an interface has a feature, as Vivado configures it
_HAS = {"awlock": "HAS_LOCK", "awqos": "HAS_QOS", "awregion": "HAS_REGION",
        "awcache": "HAS_CACHE", "awprot": "HAS_PROT", "awburst": "HAS_BURST",
        "wstrb": "HAS_WSTRB", "bresp": "HAS_BRESP", "rresp": "HAS_RRESP",
        "arlock": "HAS_LOCK", "arqos": "HAS_QOS", "arregion": "HAS_REGION",
        "arcache": "HAS_CACHE", "arprot": "HAS_PROT", "arburst": "HAS_BURST"}


def integrator(leaf) -> bool:
    """A leaf Vivado makes only inside a block design: a procedure, or an
    IP its description marks ``integrator``."""
    v = leaf.get("vivado", {}) if isinstance(leaf, dict) else {}
    return "tcl" in v or bool(v.get("integrator"))


def groups(design, top: str) -> dict:
    """``{module: [leaf paths]}`` -- every composite's integrator leaves,
    one block design each, its wrapper module named for the design."""
    by_parent = {}
    for path, inst in design.instances.items():
        if integrator(inst.leaf):
            by_parent.setdefault(path.rpartition(".")[0], []).append(path)
    out = {}
    for i, (parent, paths) in enumerate(sorted(by_parent.items())):
        name = f"{top}_bd" if len(by_parent) == 1 else f"{top}_bd{i}"
        out[f"{name}_wrapper"] = paths
    return out


def _axi_config(spec) -> dict:
    """An AXI interface port's properties, read from the signals it has:
    the shape the far end states, so Vivado builds what it meets."""
    sigs = spec[2]
    has_w = any(s.startswith("aw") for s in sigs)
    has_r = any(s.startswith("ar") for s in sigs)
    lite = not ({"awlen", "arlen"} & set(sigs))
    cfg = {"PROTOCOL": "AXI4LITE" if lite else
           ("AXI3" if "wid" in sigs else "AXI4"),
           "READ_WRITE_MODE": ("READ_WRITE" if has_w and has_r else
                               "WRITE_ONLY" if has_w else "READ_ONLY"),
           "DATA_WIDTH": (sigs.get("wdata") or sigs.get("rdata"))[1],
           "ADDR_WIDTH": (sigs.get("awaddr") or sigs.get("araddr"))[1]}
    if not lite:
        ident = sigs.get("awid") or sigs.get("arid")
        cfg["ID_WIDTH"] = ident[1] if ident else 0
        for prop in sorted(set(_HAS.values())):
            cfg[prop] = int(any(_HAS[s] == prop for s in sigs if s in _HAS))
    return cfg

def emit_rtl(design, *, out: Path, part: str, board_part: str,
             board_files: Path, ip_repos: list[Path], name: str | None = None
             ):
    """``(tcl, files, facts)``: the Tcl that builds ``design`` from its
    Verilog in a project called ``name``; the Verilog to write into the
    build's ``hdl`` folder, by file name; and what the later steps read --
    the top module and the block designs to generate."""
    out = Path(out)
    proj = name or design.name
    leaves = design.instances
    cell = cell_names(design)
    groups_ = groups(design, design.name)
    member = {p: g for g, paths in groups_.items() for p in paths}
    written = modules(design, groups_)
    gports = group_ports(design, groups_)
    files = {f"{m}.v": text for m, text in written}

    sources, seen = [], set()
    for inst in leaves.values():
        obj = inst.leaf if isinstance(inst.leaf, dict) else {}
        found = [source_file(inst.folder, f) for f in obj.get("sources", [])]
        found += [out / "hdl" / f for f in obj.get("generated", [])]
        for f in found:
            f = f.resolve()
            if f not in seen:
                seen.add(f)
                sources.append(f)
    sources += [out / "hdl" / f for f in files]

    L = []
    w = L.append
    w("# GENERATED by np2hw.toolchain.vivado.rtl from the design's JSON -- "
      "do not edit.")
    w(f"# {design.ref}")
    w("set out [file normalize [lindex $argv 0]]")
    w(f"set_param board.repoPaths {tcl(str(board_files))}")
    w(f"create_project {proj} [file join $out build {proj}] -part {part} "
      "-force")
    w(f"set_property board_part {board_part} [current_project]")
    w("set_property ip_repo_paths [list "
      + " ".join(tcl(str(p)) for p in ip_repos) + "] [current_project]")
    w("update_ip_catalog")
    w("add_files " + " ".join(tcl(str(f)) for f in sources))
    for c in design.constraints:
        w(f"add_files -fileset constrs_1 {tcl(str(c['file']))}")
        if c["scoped_to"]:
            w(f"set_property SCOPED_TO_REF {c['scoped_to']} "
              f"[get_files {tcl(str(c['file']))}]")
            w(f"set_property PROCESSING_ORDER LATE "
              f"[get_files {tcl(str(c['file']))}]")

    # Each vendor leaf outside a block design: an IP by its cell's name.
    for path, inst in leaves.items():
        leaf = inst.leaf if isinstance(inst.leaf, dict) else {}
        v = leaf.get("vivado", {})
        if path in member or "ip" not in v:
            continue
        vendor_, library, ip_name, *version = v["ip"].split(":")
        w(f"create_ip -vendor {vendor_} -library {library} -name {ip_name}"
          + (f" -version {version[0]}" if version else "")
          + f" -module_name {cell[path]}")
        props = {**leaf.get("implementation_config", {}), **inst.build,
                 **inst.config}
        if props:
            w("set_property -dict [list " + " ".join(
                f"CONFIG.{k} {tcl(val)}" for k, val in props.items())
              + f"] [get_ips {cell[path]}]")
        w(f"set_property generate_synth_checkpoint false "
          f"[get_files {cell[path]}.xci]")
        w(f"generate_target all [get_ips {cell[path]}]")

    # The described vendor blocks' pins as the tool built them, for
    # np2hw.toolchain.vivado.vendor_check: a block design's members from
    # the block design, every other one from the elaborated Verilog.
    checked = [p for p, inst in leaves.items() if vendor(inst.leaf)]
    w(f"file mkdir {tcl(str(out / 'generated'))}")
    w(f"set dump [open {tcl(str(out / 'generated' / 'vendor_ports.txt'))} w]")

    bds = []
    for module, paths in groups_.items():
        bd = module[:-len("_wrapper")]
        bds.append(bd)
        w("")
        w(f"create_bd_design {bd}")
        sourced = set()
        for path in paths:
            inst = leaves[path]
            v = inst.leaf["vivado"]
            if "tcl" in v:
                src = (inst.folder / v["source"]).resolve()
                if src not in sourced:
                    sourced.add(src)
                    w(f"source {tcl(str(src))}")
                w(f"{v['tcl']} {cell[path]} "
                  f"{tcl({**inst.build, **inst.config})}")
            else:
                w(f"create_bd_cell -type ip -vlnv {v['ip']} {cell[path]}")
                props = {**inst.build, **inst.config}
                if props:
                    w("set_property -dict [list " + " ".join(
                        f"CONFIG.{k} {tcl(val)}" for k, val in props.items())
                      + f"] [get_bd_cells {cell[path]}]")
        inside = set(paths)

        def pin(path, port):
            leaf = leaves[path].leaf
            mapped = leaf.get("port_map", {}).get(port, port) \
                if isinstance(leaf, dict) else port
            return f"{cell[path]}/{mapped}"

        def member_bundle(path, port):
            net = design.netlist["instances"][path]
            return port in (net["bundles"] or {}) if net["ports"] else None

        # between members, as the design wires them
        for a, b in design.edges:
            pa, _, qa = a.rpartition(".")
            pb, _, qb = b.rpartition(".")
            if pa in inside and pb in inside:
                bundle = member_bundle(pa, qa) or member_bundle(pb, qb)
                if bundle is None:
                    # neither states the port: an interface by its name
                    bundle = qa.endswith("AXI") or qb.endswith("AXI")
                cmd = "connect_bd_intf_net [get_bd_intf_pins" if bundle \
                    else "connect_bd_net [get_bd_pins"
                end = "get_bd_intf_pins" if bundle else "get_bd_pins"
                w(f"{cmd} {pin(pa, qa)}] [{end} {pin(pb, qb)}]")
        # to the rest of the design: ports named as the Verilog has them
        for port, rec in gports[module].items():
            spec, (mpath, mport) = rec["spec"], rec["member"]
            if spec[0] == "signal":
                d = {"input": "I", "output": "O", "inout": "IO"}[spec[1]]
                rng = f" -from {spec[2] - 1} -to 0" if spec[2] > 1 else ""
                w(f"create_bd_port -dir {d}{rng} {port}")
                w(f"connect_bd_net [get_bd_ports {port}] "
                  f"[get_bd_pins {pin(mpath, mport)}]")
            elif {"awaddr", "araddr"} & set(spec[2]):
                mode = "Slave" if spec[1] == "inputs" else "Master"
                w(f"create_bd_intf_port -mode {mode} -vlnv {AXIMM} {port}")
                w("set_property -dict [list " + " ".join(
                    f"CONFIG.{k} {tcl(v)}" for k, v
                    in _axi_config(spec).items())
                  + f"] [get_bd_intf_ports {port}]")
                w(f"connect_bd_intf_net [get_bd_intf_ports {port}] "
                  f"[get_bd_intf_pins {pin(mpath, mport)}]")
            else:
                # any other bundle, signal by signal, by the member's own
                # pin names: no interface naming between us and the ports
                pins = vendor_pins(leaves[mpath].leaf, mpath)
                for sfx, (d, width) in spec[2].items():
                    signal = next(s for s in pins
                                  if s == f"{mport}_{sfx}" or s == sfx)
                    dd = {"input": "I", "output": "O", "inout": "IO"}[d]
                    rng = f" -from {width - 1} -to 0" if width > 1 else ""
                    w(f"create_bd_port -dir {dd}{rng} {port}_{sfx}")
                    w(f"connect_bd_net [get_bd_ports {port}_{sfx}] "
                      f"[get_bd_pins {cell[mpath]}/{pins[signal][0]}]")
        w("validate_bd_design")
        mine = [cell[p] for p in paths if p in checked]
        if mine:
            w("foreach c [list " + " ".join(mine) + "] {")
            w('    puts $dump "CELL $c"')
            w("    foreach p [get_bd_pins -of [get_bd_cells $c]] {")
            w('        puts $dump "PIN [get_property NAME $p] '
              '[get_property DIR $p] [get_property LEFT $p] '
              '[get_property RIGHT $p]"')
            w("    }")
            w("}")
        w("save_bd_design")
        w(f"make_wrapper -files [get_files {bd}.bd] -import")

    w("")
    w(f"set_property top {design.name} [current_fileset]")
    w("update_compile_order -fileset sources_1")
    rest = [cell[p] for p in checked if p not in member]
    if rest:
        # elaborated, the hierarchy kept: each IP a cell by its module name
        w(f"synth_design -rtl -top {design.name} -name elaborated")
        w("foreach c [list " + " ".join(rest) + "] {")
        w('    set it [lindex [get_cells -hierarchical '
          '-filter "REF_NAME == $c"] 0]')
        w('    puts $dump "CELL $c"')
        w("    set seen {}")
        w("    foreach p [get_pins -of_objects $it] {")
        w("        set bus [get_property BUS_NAME $p]")
        w("        set n [expr {$bus ne {} ? $bus : "
          "[get_property REF_PIN_NAME $p]}]")
        w("        if {$n in $seen} continue")
        w("        lappend seen $n")
        w("        set d [string map {INOUT IO IN I OUT O} "
          "[get_property DIRECTION $p]]")
        w("        if {$bus ne {}} {")
        w("            set a [get_property BUS_START $p]")
        w("            set b [get_property BUS_STOP $p]")
        w('            puts $dump "PIN $n $d [expr {max($a, $b)}] '
          '[expr {min($a, $b)}]"')
        w("        } else {")
        w('            puts $dump "PIN $n $d"')
        w("        }")
        w("    }")
        w("}")
        w("close_design")
    w("close $dump")
    w('puts "RTL_DONE"')
    facts = {"top": design.name, "block_designs": bds}
    return "\n".join(L) + "\n", files, facts
