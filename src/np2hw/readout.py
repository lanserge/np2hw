"""A stream's frames, read by software: the readout leaf.

What a design wires a stream into when software is to read its frames --
a fold's statistics, most often: each frame written into a memory on the
stream's clock and read over AXI4-Lite on the bus's (``np2hw_readout``,
a fixed module; ``docs/clock-crossings.md``). What varies with the stream
is its shape -- the entries a frame, the values an entry, their width --
and that is all this generates: the window's layout and address width,
which is the window a bus decoder places it at, and the wrapper setting
them. A design states the shape as the stream's traced facts
(``isp.stats.max_width``, ...), never as numbers of its own.
"""
from __future__ import annotations

import zlib

from np2hw.ports import Pin, header, published


#: a stream that carries no context: its CTX member tied off
ZERO = "1'b0"


def _pow2(n: int) -> int:
    return 1 << max(0, (int(n) - 1).bit_length())


def layout(rows: int, cols: int, channels: int, bits: int,
           signed: bool) -> dict:
    """Where a frame's entries sit in the window, as 32-bit words: word 0
    the frames published, then a slot of `slot_words` an entry, row-major,
    each value `value_words` words of it, two's complement where signed --
    the facts software reads its frames by."""
    entries = int(rows) * int(cols)
    value_words = _pow2(-(-int(bits) // 32))
    slot_words = _pow2(int(channels)) * value_words
    words = (entries + 1) * slot_words
    return {"rows": int(rows), "cols": int(cols), "entries": entries,
            "channels": int(channels), "bits": int(bits),
            "signed": bool(signed), "value_words": value_words,
            "slot_words": slot_words, "count_word": 0,
            "addr_bits": max(12, (words * 4 - 1).bit_length())}


def readout(rows, cols, channels, bits, signed=False, context_bits=0):
    """A stream's frames, read by software over AXI4-Lite."""
    shape = layout(rows, cols, channels, bits, signed)
    if shape["channels"] > 1 and shape["signed"]:
        raise ValueError("a signed value is one channel's: a stream's "
                         "channels are unsigned")
    data_bits = shape["channels"] * shape["bits"]
    aw = shape["addr_bits"]
    tag = zlib.crc32(repr((sorted(shape.items()), context_bits))
                     .encode()) & 0xFFFFFF
    module = f"np2hw_readout_{tag:06x}"
    from np2hw.stream import clock_attribute, reset_attribute, stream_pins
    from np2hw.verilog import axil_slave_pins
    pins = [Pin("clk", "input", attribute=clock_attribute("clk", ["in"],
                                                          "rst")),
            Pin("rst", "input", attribute=reset_attribute("rst")),
            *stream_pins("in", "in", data_bits,
                         flags=("sof", "eol", "last"),
                         ctx_bits=int(context_bits)),
            Pin("aclk", "input", attribute=clock_attribute(
                "aclk", ["s_axi"], "aresetn")),
            Pin("aresetn", "input", attribute=reset_attribute(
                "aresetn", active_low=True)),
            *axil_slave_pins(aw, bundle="s_axi", prefix="s_axi")]
    ctx = max(1, int(context_bits))
    L = ["// Copyright 2026 Serge Rabyking",
         "// SPDX-License-Identifier: MIT",
         "//",
         f"// {module} -- np2hw_readout for a stream of {shape['rows']} x "
         f"{shape['cols']} entries, {shape['channels']} value(s) of "
         f"{shape['bits']} bits each.",
         "// Generated by np2hw.readout; the window's words: 0 the frames "
         f"published, then {shape['slot_words']} an entry."]
    L += header(module, pins)
    L.append("    np2hw_readout #(")
    L.append(f"        .DATA_BITS({data_bits}), .CTX_BITS({ctx}), "
             f".FIELD({shape['bits']}),")
    L.append(f"        .SIGNED({int(shape['signed'])}), "
             f".ENTRIES({shape['entries']}), "
             f".VALUE_WORDS({shape['value_words']}), "
             f".SLOT_WORDS({shape['slot_words']}), .AW({aw})")
    L.append("    ) core (")
    L.append("        .clk(clk), .rst(rst), .in_valid(in_valid), "
             ".in_ready(in_ready),")
    L.append("        .in_data(in_data), .in_sof(in_sof), .in_eol(in_eol), "
             ".in_last(in_last),")
    L.append(f"        .in_ctx({'in_ctx' if context_bits else ZERO}),")
    L.append("        .aclk(aclk), .aresetn(aresetn),")
    names = [p.name for p in pins if p.name.startswith("s_axi_")]
    L.append("        " + ",\n        ".join(f".{n}({n})" for n in names))
    L.append("    );")
    L.append("endmodule")
    return {"verilog": "\n".join(L) + "\n", "module": module,
            "requires": ("np2hw_readout",),
            "interface": {"ports": published(pins)},
            "constraints": [readout_crossing(module)],
            "facts": {"layout": shape,
                      "clocks": {"in": ["clk", "rst"],
                                 "s_axi": ["aclk", "aresetn"]}}}


readout.leaf = True


def readout_crossing(module: str) -> dict:
    """The one path crossing between the readout's clocks besides its
    memory: the Gray-coded count, bounded by one period of the clock that
    samples it, as np2hw_cdc_fifo's pointers are."""
    text = "\n".join([
        "# GENERATED by np2hw.readout -- np2hw_readout's crossing, scoped to",
        "# the module. Its memory is block RAM, written on clk and read on",
        "# aclk; the frames published cross Gray coded, through two flops,",
        "# each bit bounded by one period of the clock that samples it.",
        "set_max_delay -datapath_only \\",
        "    -from [get_cells {frames_gray_reg[*]}] \\",
        "    -to [get_cells {frames_sync1_reg[*]}] \\",
        "    [get_property -min PERIOD [get_clocks -of_objects "
        "[get_cells {frames_sync1_reg[*]}]]]",
        ""])
    return {"file": f"{module}_crossing.xdc", "text": text,
            "scoped_to": "np2hw_readout", "apart": ["clk", "aclk"]}
